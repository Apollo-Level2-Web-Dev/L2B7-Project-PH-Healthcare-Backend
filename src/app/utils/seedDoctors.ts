const seedDoctors = async () => {
	const hashedPassword = await bcrypt.hash(
		DOCTOR_PASSWORD,
		Number(config.bcrypt_salt_rounds),
	);

	for (const { name, email, ...doctor } of [...doctors, ...extraDoctors]) {
		const isDoctorExist = await prisma.user.findUnique({ where: { email } });

		if (isDoctorExist) {
			console.log(`Skipped (already exists): ${email}`);
			continue;
		}

		// No id passed anywhere — Prisma generates the uuid for both rows.
		await prisma.user.create({
			data: {
				name,
				email,
				password: hashedPassword,
				role: Role.DOCTOR,
				needPasswordChange: false,
				emailVerified: true,
				doctor: {
					create: {
						name,
						email,
						...doctor,
						verificationStatus: DoctorVerificationStatus.APPROVED,
					},
				},
			},
		});

		console.log(`Created: ${name} <${email}>`);
	}

	console.log(`Done. Login password for all seeded doctors: ${DOCTOR_PASSWORD}`);
};

